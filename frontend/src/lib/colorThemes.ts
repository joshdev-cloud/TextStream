/**
 * colorThemes.ts — Central theme definitions for the MonkeyType-style color palette system.
 *
 * Contains 14 curated preset themes (7 dark, 7 light) plus types for DIY custom themes.
 * Each theme provides a full set of CSS custom property overrides that map to the
 * existing design system variables in styles.css.
 */

/* ──────────────────────────── Types ──────────────────────────── */

export interface ThemePreview {
  bg: string;
  primary: string;
  accent: string;
  text: string;
}

export interface ColorTheme {
  id: string;
  name: string;
  mode: "dark" | "light";
  preview: ThemePreview;
  variables: Record<string, string>;
}

export interface CustomThemeColors {
  background: string;
  foreground: string;
  primary: string;
  accent: string;
  card: string;
  border: string;
  muted: string;
}

